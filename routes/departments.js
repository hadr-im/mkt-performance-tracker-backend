const express = require('express');
const router = express.Router();
const { getSignups, getApplications, getMembersInfo, applyFilters } = require('../services/sheets');

router.get('/', async (req, res) => {
  try {
    const { member: memberFilter, dateFrom, dateTo } = req.query;

    const [signups, applications, membersInfo] = await Promise.all([
      getSignups(),
      getApplications(),
      getMembersInfo()
    ]);

    const filteredSignups = applyFilters(signups, { member: memberFilter, dateFrom, dateTo });
    const filteredApps = applyFilters(applications, { member: memberFilter, dateFrom, dateTo });

    // Helper: Map emails to member names from signups sheet
    const emailToMember = {};
    signups.forEach(s => {
      if (s.email) emailToMember[s.email.toLowerCase().trim()] = s.memberName;
    });

    // Department-level aggregation
    const deptMap = {};
    
    // Process Signups
    filteredSignups.forEach(s => {
      const member = s.memberName || 'Unknown';
      const dept = membersInfo[member.toLowerCase().trim()] || 'Unknown';
      
      if (!deptMap[dept]) {
        deptMap[dept] = { signups: 0, applicants: new Set(), members: new Set(), universities: new Set(), timeSeries: {} };
      }
      deptMap[dept].signups++;
      if (member !== 'Unknown') deptMap[dept].members.add(member);
      if (s.university) deptMap[dept].universities.add(s.university);
      
      if (s.date) {
        const dateKey = s.date.toISOString().split('T')[0];
        deptMap[dept].timeSeries[dateKey] = (deptMap[dept].timeSeries[dateKey] || 0) + 1;
      }
    });

    // Process Applications (Linked via email to signups to get member/dept)
    filteredApps.forEach(a => {
      const member = emailToMember[a.email?.toLowerCase().trim()] || 'Unknown';
      const dept = membersInfo[member.toLowerCase().trim()] || 'Unknown';
      
      if (deptMap[dept] && a.personId) {
        deptMap[dept].applicants.add(a.personId);
      }
    });

    const departments = Object.entries(deptMap).map(([dept, data]) => ({
      department: dept,
      signups: data.signups,
      applicants: data.applicants.size,
      members: data.members.size,
      memberList: [...data.members],
      universitiesVisited: data.universities.size,
      conversionRate: data.signups > 0 ? ((data.applicants.size / data.signups) * 100).toFixed(1) : 0,
    })).sort((a, b) => b.signups - a.signups);

    // Member breakdown per department
    const memberSummary = {};
    filteredSignups.forEach(s => {
      const m = s.memberName || 'Unknown';
      const dept = membersInfo[m.toLowerCase().trim()] || 'Unknown';
      const key = `${m}||${dept}`;
      
      if (!memberSummary[key]) {
        memberSummary[key] = {
          name: m,
          department: dept,
          signups: 0,
          applications: 0,
          days: new Set(),
        };
      }
      memberSummary[key].signups++;
      if (s.date) memberSummary[key].days.add(s.date.toISOString().split('T')[0]);
      
      // Link apps
      if (s.email) {
        // This is a bit complex for a summary, but let's assume we want to show 
        // the apps generated by this member's signups.
      }
    });

    const memberBreakdown = Object.values(memberSummary).map(m => ({
      ...m,
      activeDays: m.days.size,
      days: undefined,
    })).sort((a, b) => b.signups - a.signups);

    // Time series (Continuous & 0-filled for all deps)
    const allDepts = Object.keys(deptMap).filter(d => d !== 'Unknown').sort();
    
    // Determine date range bounds
    let start, end;
    if (dateFrom && dateTo) {
      start = new Date(dateFrom);
      end = new Date(dateTo);
    } else {
      const allDates = filteredSignups.map(s => s.date).filter(Boolean).sort((a, b) => a - b);
      if (allDates.length > 0) {
        start = new Date(allDates[0]);
        end = new Date(allDates[allDates.length - 1]);
      } else {
        const today = new Date();
        start = new Date(today);
        start.setDate(today.getDate() - 30);
        end = today;
      }
    }

    // Generate continuous map for every day in range
    const timeMap = {};
    const curr = new Date(start);
    // Safety limit to avoid infinite loops if dates are invalid
    let safety = 0;
    while (curr <= end && safety < 1000) {
      const dateKey = curr.toISOString().split('T')[0];
      const entry = { date: dateKey };
      // Pre-fill every department with 0 to ensure continuous lines
      allDepts.forEach(d => entry[d] = 0);
      timeMap[dateKey] = entry;
      curr.setDate(curr.getDate() + 1);
      safety++;
    }

    // Populate with actual signup counts
    Object.entries(deptMap).forEach(([dept, data]) => {
      if (dept === 'Unknown') return;
      Object.entries(data.timeSeries).forEach(([date, count]) => {
        if (timeMap[date]) {
          timeMap[date][dept] = count;
        }
      });
    });

    const deptTimeSeries = Object.values(timeMap).sort((a, b) => a.date.localeCompare(b.date));

    res.json({
      departments,
      memberBreakdown,
      deptTimeSeries,
      allDepts,
    });
  } catch (err) {
    console.error('Departments error:', err);
    res.status(500).json({ error: err.message });
  }
});

module.exports = router;
